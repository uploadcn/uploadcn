// Generates components/icons/<library>.ts: every icon referenced by an
// <IconPlaceholder> in the registry or the site, one module per icon
// library. A page only downloads the library it shows: Lucide (the default)
// with the page, the others when someone picks them in Customize.
import {
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const LIBRARIES = {
  lucide: "lucide-react",
  tabler: "@tabler/icons-react",
  hugeicons: "@hugeicons/core-free-icons",
  phosphor: "@phosphor-icons/react",
  remixicon: "@remixicon/react",
}

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry)
    if (statSync(full).isDirectory()) yield* walk(full)
    else if (/\.tsx?$/.test(entry)) yield full
  }
}

const used = Object.fromEntries(
  Object.keys(LIBRARIES).map((lib) => [lib, new Set()])
)
const element = /<IconPlaceholder\b([\s\S]*?)\/>/g
const attribute = /(lucide|tabler|hugeicons|phosphor|remixicon)="([^"]+)"/g
for (const dir of ["registry", "components"]) {
  for (const file of walk(path.join(root, dir))) {
    const source = readFileSync(file, "utf8")
    for (const [, attrs] of source.matchAll(element)) {
      for (const [, lib, name] of attrs.matchAll(attribute)) used[lib].add(name)
    }
  }
}

const header = "// Generated by scripts/gen-icon-map.mjs. Do not edit.\n\n"
for (const [lib, pkg] of Object.entries(LIBRARIES)) {
  const names = [...used[lib]].sort()
  const imports = `import {\n${names.map((name) => `  ${name},`).join("\n")}\n} from "${pkg}"\n`
  let out = header
  if (lib === "hugeicons") {
    // Hugeicons ships icon data, not components: wrap each one.
    out +=
      'import * as React from "react"\nimport { HugeiconsIcon } from "@hugeicons/react"\n'
    out += `${imports}\n`
    out +=
      'type Props = Omit<React.ComponentProps<typeof HugeiconsIcon>, "icon">\n\n'
    out +=
      'const wrap = (icon: React.ComponentProps<typeof HugeiconsIcon>["icon"]) =>\n'
    out += "  function Icon(props: Props) {\n"
    out +=
      "    return React.createElement(HugeiconsIcon, { icon, strokeWidth: 2, ...props })\n"
    out += "  }\n\n"
    out += `export const icons = {\n${names.map((name) => `  ${name}: wrap(${name}),`).join("\n")}\n}\n`
  } else {
    out += `${imports}\nexport const icons = {\n${names.map((name) => `  ${name},`).join("\n")}\n}\n`
  }
  writeFileSync(path.join(root, `components/icons/${lib}.ts`), out)
}
rmSync(path.join(root, "components/icons/icon-map.ts"), { force: true })

console.log(
  Object.entries(used)
    .map(([lib, names]) => `${lib}: ${names.size}`)
    .join(", ")
)
